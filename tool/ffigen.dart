// Regenerates lib/src/bindings/audiocpp.g.dart from the vendored header.
//
//   dart run tool/ffigen.dart
//
// Requires libclang (see https://pub.dev/packages/ffigen#requirements).

import 'dart:io';

import 'package:ffigen/ffigen.dart';

/// Accessors that only read state already held by a handle: they never block,
/// never call back into Dart, and are safe to mark as leaf calls.
const _leafPrefixes = [
  'audiocpp_abi_version',
  'audiocpp_build_version',
  'audiocpp_last_error',
  'audiocpp_status_string',
  'audiocpp_registry_family',
  'audiocpp_task_',
  'audiocpp_model_family',
  'audiocpp_model_description',
  'audiocpp_model_supports',
  'audiocpp_model_language',
  'audiocpp_model_option',
  'audiocpp_session_family',
  'audiocpp_result_',
  'audiocpp_event_',
  'audiocpp_stream_policy',
];

Future<void> main() async {
  final packageRoot = Uri.file(Platform.script.toFilePath()).resolve('../');
  final header = packageRoot.resolve('third_party/audiocpp/audiocpp.h');
  final generator = FfiGenerator(
    input: Input(
      entryPoints: [header],
      include: (uri) => uri == header,
      // The upstream header has `model_specs/*.json` inside a block comment.
      compilerOptions: ['-Wno-comment'],
      appendCompilerOptions: true,
    ),
    output: Output(
      dart: DartOutput(
        path: packageRoot.resolve('lib/src/bindings/audiocpp.g.dart'),
      ),
      preamble: '''
// Generated by tool/ffigen.dart from third_party/audiocpp/audiocpp.h.
// Do not edit by hand.
// ignore_for_file: type=lint, unused_import''',
      style: const NativeExternalBindings(
        assetId: 'package:audio_cpp_dart/audiocpp',
      ),
    ),
    visitors: [
      Visitor(
        func: (node) {
          node.isIncluded = node.originalName.startsWith('audiocpp_');
          final name = node.originalName;
          // *_free functions are attached to NativeFinalizers.
          if (name.endsWith('_free')) node.exposeSymbolAddress = true;
          if (_leafPrefixes.any(name.startsWith)) node.isLeaf = true;
        },
        struct: (node) =>
            node.isIncluded = node.originalName.startsWith('audiocpp_'),
        enumClass: (node) {
          node.isIncluded = node.originalName.startsWith('audiocpp_');
          // Every audiocpp enum fits in 0..255, so the 32-bit int/unsigned int
          // that GCC, Clang and MSVC pick for it is ABI-identical.
          node.silenceWarning = true;
        },
        macroConstant: (node) =>
            node.isIncluded = node.originalName.startsWith('AUDIOCPP_ABI'),
        typealias: (node) {},
      ),
    ],
  );
  await generator.generate();
}
